"""极简计算器模块（sample_project 的示例代码）。
"""

from __future__ import annotations


def add(a: float, b: float) -> float:
    """返回两数之和。"""
    return a + b


def subtract(a: float, b: float) -> float:
    """返回两数之差。"""
    return a - b


def multiply(a: float, b: float) -> float:
    """返回两数之积。"""
    return a * b


def divide(a: float, b: float) -> float:
    """返回 a 除以 b 的结果。"""
    return a / b
